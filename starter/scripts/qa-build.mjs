import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';

const dist = new URL('../dist/', import.meta.url);
const source = new URL('../src/', import.meta.url);
const path = (relative) => new URL(relative, dist);
const sourcePath = (relative) => new URL(relative, source);
const exists = (relative) => existsSync(path(relative));
const html = (relative) => readFileSync(path(relative), 'utf8');

assert.ok(exists('uploads/Screenshot_291.png'), 'Uploaded CMS image must be copied into dist/uploads.');

const portfolioRoute = exists('portfolio/index.html') ? 'portfolio/index.html' : 'portfolio.html';
assert.ok(exists(portfolioRoute), 'CMS-created /portfolio/ page must be generated by Astro.');
const portfolioHtml = html(portfolioRoute);
const portfolioSource = readFileSync(sourcePath('content/pages/portfolio.md'), 'utf8');
const heroImageLine = portfolioSource.split('\n').find((line) => line.startsWith('    image:'));
const heroImage = heroImageLine?.slice('    image:'.length).trim();
assert.ok(heroImage?.startsWith('https://'), 'Portfolio CMS content must define an absolute hero image URL.');
assert.ok(portfolioHtml.includes(heroImage.split('?')[0]), 'Portfolio hero image from CMS content must render.');

for (const route of ['about', 'contact', 'blog', 'services']) {
  assert.ok(exists(`${route}/index.html`) || exists(`${route}.html`), `Expected static route /${route}/ to be generated.`);
}

assert.ok(portfolioHtml.includes('site-header-inner'), 'Premium site header must render.');
assert.ok(portfolioHtml.includes('site-nav-mobile'), 'Accessible mobile navigation must render.');
assert.ok(portfolioHtml.includes('aria-current="page"'), 'Current navigation item must be identified.');
assert.ok(portfolioHtml.includes('site-footer-grid'), 'Structured footer columns must render.');
assert.ok(portfolioHtml.includes('site-footer-links'), 'Footer navigation must render.');
assert.ok(portfolioHtml.includes('prefers-reduced-motion'), 'Reduced-motion styles must be included in generated CSS.');

const footerStart = portfolioHtml.indexOf('<footer');
const footerEnd = portfolioHtml.indexOf('</footer>');
assert.ok(footerStart >= 0 && footerEnd > footerStart, 'Site footer must be rendered.');
const footerHtml = portfolioHtml.slice(footerStart, footerEnd + '</footer>'.length);
const siteSettings = JSON.parse(readFileSync(sourcePath('data/site.json'), 'utf8'));
assert.ok(footerHtml.includes(siteSettings.site_name), 'Footer must display the current Site Settings site name.');

for (const social of siteSettings.social_links ?? []) {
  if (!social.label || !social.url) continue;
  const url = social.url.trim();
  const normalizedUrl = url.startsWith('http://') || url.startsWith('https://') ? url : `https://${url.replace(/^\/+/, '')}`;
  assert.ok(footerHtml.includes(normalizedUrl), `Configured social profile "${social.label}" must render in the footer.`);
}

const blogRoute = exists('blog/index.html') ? html('blog/index.html') : html('blog.html');
assert.ok(blogRoute.includes('Ideas &amp; insights') || blogRoute.includes('Ideas & insights'), 'Blog listing eyebrow must render.');
assert.ok(blogRoute.includes('card-meta'), 'Blog listing metadata must render.');

const serviceRoute = exists('services/index.html') ? html('services/index.html') : html('services.html');
assert.ok(serviceRoute.includes('Featured service'), 'Featured services must be visually identified.');

assert.ok(exists('robots.txt'), 'robots.txt must be generated.');
assert.ok(exists('sitemap-index.xml'), 'Sitemap index must be generated.');

console.log('Build QA passed: routes, CMS media/content, responsive navigation, active state, structured footer, reduced motion, blog metadata, featured services, robots.txt and sitemap.');
